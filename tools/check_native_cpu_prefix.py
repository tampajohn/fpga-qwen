#!/usr/bin/env python3
"""Guarded real-process canonical-prefix equivalence; no throughput claims."""
import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import struct
import subprocess
import threading

from benchmark_guard import BenchmarkGate
from chat_protocol import ChatRequest
from native_cpu_chat import NativeCPUChat

ROOT = Path(__file__).resolve().parents[1]
VOCABULARY = 151936
CHUNK = 512


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


class Tokenizer:
    # Fixed token fixtures deliberately bypass text tokenization. Preserve every
    # returned ID in text so adapter text equivalence is also observable.
    def decode(self, ids, skip_special_tokens=True):
        return ' '.join(map(str, ids))


class Protocol:
    tokenizer = Tokenizer()


class Recorder(NativeCPUChat):
    def begin(self, directory):
        directory.mkdir()
        self.directory = directory
        self.records = []
        self.cancel_next_prefill = False
        self.cancelled_process = None

    def command(self, command, cancel, *args, **kwargs):
        timer = None
        if command.startswith('prefill ') and self.cancel_next_prefill:
            self.cancel_next_prefill = False
            self.cancelled_process = self.process
            timer = threading.Timer(.005, cancel.set)
            timer.start()
        try:
            response = super().command(command, cancel, *args, **kwargs)
        finally:
            if timer is not None:
                timer.cancel()
                timer.join()
        if command.startswith(('prefill ', 'step ')):
            path = self.directory / f'prediction-{len(self.records):03d}.f32'
            dumped = super().command('dump ' + str(path), cancel)
            require(dumped.get('ok') is True and dumped.get('count') == VOCABULARY
                    and dumped.get('position') == response.get('position'), 'Invalid dump metadata')
            payload = path.read_bytes()
            require(len(payload) == VOCABULARY * 4, 'Wrong full-logit array length')
            require(all(math.isfinite(value[0]) for value in struct.iter_unpack('<f', payload)),
                    'Nonfinite full-vocabulary logits')
            self.records.append(dict(token=response['token'], position=response['position'],
                                     path=str(path), sha256=sha(path)))
        return response


def prefix_length(left, right):
    for index, pair in enumerate(zip(left, right)):
        if pair[0] != pair[1]:
            return index
    return min(len(left), len(right))


def fixtures():
    # Independent fixed IDs, not output generated by either engine. These are
    # synthetic numerical/cache fixtures and do not measure answer quality.
    pattern = [40, 657, 264, 3465, 13, 198, 17, 11, 18, 11, 19, 13, 198]
    base = (pattern * 120)[:1537]
    cases = []
    def add(name, count, session='a', edits=()):
        ids = base[:count]
        for position, value in edits:
            ids[position] = value
        cases.append(dict(name=name, session=session, ids=ids))
    add('initial-511', 511)
    add('append-512', 512)
    add('append-513', 513)
    add('identical-513', 513)
    add('append-1024', 1024)
    add('identical-1024', 1024)
    add('append-1025', 1025)
    add('edit-after-1024', 1025, edits=[(1024, 1917)])
    add('edit-at-512', 1025, edits=[(512, 9707)])
    add('edit-at-511', 1025, edits=[(511, 9707)])
    add('session-switch', 1025, session='b')
    add('identical-new-session', 1025, session='b')
    add('shorter-prompt', 85, session='b')
    add('extend-after-short', 1025, session='b')
    return base, cases


def run_request(engine, case, decoding, directory, cancel=None):
    engine.begin(directory)
    request = ChatRequest(case['session'], case['ids'], 4, 0, decoding=decoding, seed=42)
    events = list(engine.stream(request, cancel or threading.Event()))
    require(events and events[-1].get('type') == 'done', 'Missing terminal stream event')
    done = events[-1]
    require(done['finish_reason'] in ('length', 'eos'), 'Unexpected stream finish reason')
    require(engine.records, 'No model predictions observed')
    require(isinstance(done.get('token_ids'), list)
            and len(done['token_ids']) == done['metrics']['output_tokens'],
            'Missing or inconsistent generated-token metadata')
    return dict(finish_reason=done['finish_reason'], text=done['text'],
                token_ids=done.get('token_ids'), metrics=done['metrics'],
                predictions=list(engine.records))


def compare(cached, fresh):
    require(cached['finish_reason'] == fresh['finish_reason'], 'Stop behavior changed')
    require(cached['text'] == fresh['text'] and cached['token_ids'] == fresh['token_ids'],
            'Rendered text or generated IDs changed')
    left, right = cached['predictions'], fresh['predictions']
    require(len(left) == len(right), 'Prediction count changed')
    for a, b in zip(left, right):
        require((a['token'], a['position']) == (b['token'], b['position']),
                'Prediction ID/position changed')
        require(Path(a['path']).read_bytes() == Path(b['path']).read_bytes(),
                'Full-vocabulary logits changed')
    require(fresh['metrics']['reused_prefix_tokens'] == 0, 'Fresh control reused a prefix')


def cli_rewind_checks(binary, weights, directory):
    # Error cases are intentional and read through raw CLI, because the browser
    # adapter correctly closes on protocol errors. Every error must reset state.
    commands = ['prefill 9707 11 1917', 'rewind 3', 'stats',
                'dump ' + str(directory / 'invalid-equal.f32'), 'stats',
                'prefill 9707 11 1917', 'rewind 0', 'stats',
                'prefill 9707 11 1917', 'rewind -1', 'stats',
                'prefill 9707 11 1917', 'rewind 4', 'stats',
                'prefill 9707 11 1917', 'rewind nope', 'stats', 'quit']
    result = subprocess.run([str(binary), '--weights', str(weights), '--threads', '12',
                             '--prefill-threads', '6', '--context', '4096'],
                            input='\n'.join(commands) + '\n', text=True, capture_output=True,
                            timeout=180, env=dict(os.environ, VECLIB_MAXIMUM_THREADS='6'))
    (directory / 'cli-stdout.jsonl').write_text(result.stdout)
    (directory / 'cli-stderr.log').write_text(result.stderr)
    require(result.returncode == 0, 'Raw CLI did not exit cleanly')
    rows = [json.loads(line) for line in result.stdout.splitlines()]
    require(len(rows) == len(commands) + 1, 'Unexpected raw CLI response count')
    require(rows[0].get('prefix_reuse') is True and rows[0].get('prefix_reuse_chunk') == CHUNK,
            'CLI does not advertise canonical prefix reuse')
    answers = rows[1:]
    for index in (1, 2):
        require(answers[index].get('position') == 3, 'Rewind to current position failed')
    require('error' in answers[3] and not (directory / 'invalid-equal.f32').exists(),
            'Rewind to same position did not invalidate logits')
    for index in (4, 6, 7, 10, 13, 16):
        require(answers[index].get('position') == 0, 'Rewind/error did not clear position')
    for index in (9, 12, 15):
        require('error' in answers[index] and answers[index].get('position') == 0,
                'Invalid rewind did not reset context')
    return dict(passed=True, commands=commands, responses=rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--binary', type=Path, required=True)
    parser.add_argument('--weights', type=Path, default=ROOT / 'build/native-cpu/weights.bin')
    parser.add_argument('--directory', type=Path, required=True)
    parser.add_argument('--guard-state-dir', type=Path, default=ROOT / 'build/benchmark-status')
    args = parser.parse_args()
    guard = args.guard_state_dir.resolve()
    metadata = json.loads((guard / 'run.json').read_text())
    require(BenchmarkGate(guard).status()['running'] and metadata.get('pid') == os.getppid(),
            'Run directly under benchmark_guard.py')
    binary, weights, directory = args.binary.resolve(), args.weights.resolve(), args.directory.resolve()
    directory.mkdir(parents=True, exist_ok=False)
    report = dict(completed=False, passed=False, gpu=False, pytorch=False,
                  performance_claim_eligible=False, cases=[], checks={},
                  scope='Exact cached/fresh predictions and full logits on synthetic fixed IDs; '
                        'canonical 512-token chunks, greedy and seed42 chat. No answer-quality or timing claim.')
    def save():
        temporary = directory / 'report.pending.json'
        temporary.write_text(json.dumps(report, indent=2) + '\n')
        temporary.replace(directory / 'report.json')
    cached = Recorder(Protocol(), binary=binary, weights=weights, reuse_prefix=True)
    fresh = Recorder(Protocol(), binary=binary, weights=weights, reuse_prefix=False)
    try:
        paths = [binary, binary.parent / 'manifest.json', weights,
                 Path(str(weights) + '.index'), Path(str(weights) + '.manifest.json'),
                 Path(__file__).resolve(), ROOT / 'tools/native_cpu_chat.py', ROOT / 'tools/chat_protocol.py']
        report['inputs'] = {str(path): sha(path) for path in paths}
        base, cases = fixtures()
        report['fixtures'] = cases
        save()
        for decoding in ('greedy', 'chat'):
            cached.close()
            previous = None
            for case in cases:
                name = decoding + '-' + case['name']
                expected = 0
                if previous is not None and previous['session'] == case['session']:
                    limit = min(prefix_length(previous['ids'], case['ids']),
                                len(previous['ids']) // CHUNK * CHUNK, len(case['ids']) - 1)
                    expected = limit // CHUNK * CHUNK
                got = run_request(cached, case, decoding, directory / (name + '-cached'))
                control = run_request(fresh, case, decoding, directory / (name + '-fresh'))
                compare(got, control)
                require(got['metrics']['reused_prefix_tokens'] == expected,
                        f'{name}: expected {expected} reused tokens')
                report['cases'].append(dict(name=name, prompt_tokens=len(case['ids']),
                                           expected_reuse=expected, cached=got, fresh=control, passed=True))
                previous = case
                save()
        report['checks']['boundary_edit_identical_session_exact'] = True
        require(any(len(case['cached']['predictions']) > 1 and case['expected_reuse'] > 0
                    for case in report['cases']), 'Fixtures never exercised decode after reuse')
        # The cached adapter holds a >1024-token prefix from the preceding case.
        # Cancel an actual append, confirm reaping, and verify the next request is
        # fresh and exactly matches the cache-disabled control.
        cached.begin(directory / 'cancel-inflight')
        cached.cancel_next_prefill = True
        cancel = threading.Event()
        request = ChatRequest('b', base, 4, 0, decoding='chat', seed=42)
        events = list(cached.stream(request, cancel))
        require(cancel.is_set() and events[-1].get('finish_reason') == 'stopped',
                'Expected actual in-flight cancellation')
        require(cached.cancelled_process is not None and cached.cancelled_process.poll() is not None
                and cached.process is None, 'Cancellation did not reap/invalidate native process')
        after = dict(name='after-cancel', session='b', ids=base[:1025])
        got = run_request(cached, after, 'chat', directory / 'after-cancel-cached')
        control = run_request(fresh, after, 'chat', directory / 'after-cancel-fresh')
        compare(got, control)
        require(got['metrics']['reused_prefix_tokens'] == 0, 'Restart reused invalid cache')
        report['checks']['cancel_reap_restart_exact'] = dict(passed=True, cached=got, fresh=control)
        cached.close(); fresh.close()
        report['checks']['cli_rewind'] = cli_rewind_checks(binary, weights, directory)
        require(all(sha(Path(path)) == digest for path, digest in report['inputs'].items()),
                'Immutable inputs or checker dependencies changed')
        report.update(completed=True, passed=True)
    except BaseException as error:
        report['error'] = dict(type=type(error).__name__, message=str(error))
        raise
    finally:
        cached.close(); fresh.close()
        save()
    print(json.dumps(dict(passed=True, cases=len(report['cases']), directory=str(directory))))


if __name__ == '__main__':
    main()
